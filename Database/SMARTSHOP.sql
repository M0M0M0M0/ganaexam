IF DB_ID(N'SMARTSHOP') IS NULL
    CREATE DATABASE SMARTSHOP;
GO

USE SMARTSHOP;
GO

IF OBJECT_ID(N'dbo.Review', N'U') IS NOT NULL DROP TABLE dbo.Review;
IF OBJECT_ID(N'dbo.Product', N'U') IS NOT NULL DROP TABLE dbo.Product;
GO

CREATE TABLE dbo.Product
(
    ProductId   INT            NOT NULL CONSTRAINT PK_Product PRIMARY KEY,
    ProductName NVARCHAR(128)  NOT NULL,
    Category    NVARCHAR(64)   NOT NULL,
    Price       DECIMAL(18, 2) NOT NULL,
    Features    NVARCHAR(512)  NOT NULL,
    Description NVARCHAR(MAX)  NULL          -- generated by Gemini
);
GO

CREATE TABLE dbo.Review
(
    ReviewId     INT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_Review PRIMARY KEY,
    ProductId    INT            NOT NULL
        CONSTRAINT FK_Review_Product_ProductId REFERENCES dbo.Product (ProductId) ON DELETE CASCADE,
    CustomerName NVARCHAR(64)   NOT NULL,
    Content      NVARCHAR(1000) NOT NULL,
    Rating       INT            NOT NULL CONSTRAINT CK_Review_Rating CHECK (Rating BETWEEN 1 AND 5),
    Sentiment    NVARCHAR(16)   NOT NULL,    -- Positive / Negative / Neutral (from Gemini)
    Score        FLOAT          NOT NULL,    -- 0.0 - 1.0 (from Gemini)
    Summary      NVARCHAR(256)  NOT NULL,    -- from Gemini
    CreatedAt    DATETIME       NOT NULL
);
GO

CREATE INDEX IX_Review_ProductId ON dbo.Review (ProductId);
GO

