-- Query used by requirement 4 (getreviewreport)
SELECT ROW_NUMBER() OVER (ORDER BY p.ProductId)                       AS [No],
       p.ProductName                                                  AS [Product name],
       COUNT(*)                                                       AS [Total reviews],
       SUM(CASE WHEN r.Sentiment = N'Positive' THEN 1 ELSE 0 END)     AS [Positive],
       SUM(CASE WHEN r.Sentiment = N'Negative' THEN 1 ELSE 0 END)     AS [Negative],
       SUM(CASE WHEN r.Sentiment = N'Neutral'  THEN 1 ELSE 0 END)     AS [Neutral],
       CAST(ROUND(AVG(CAST(r.Rating AS FLOAT)), 1) AS DECIMAL(3, 1))  AS [Average rating]
FROM dbo.Product p
JOIN dbo.Review r ON r.ProductId = p.ProductId
GROUP BY p.ProductId, p.ProductName
ORDER BY p.ProductId;
GO
